import { PGlite } from "@electric-sql/pglite";
import { writeFileSync } from "node:fs";
const conf = "shared_buffers=8MB\nwal_buffers=256kB\nmax_wal_size=64MB\nmin_wal_size=32MB\nwork_mem=1MB\nmaintenance_work_mem=8MB\n";
const variant = process.argv[2] ?? "seg1";
const opts = variant === "seg1" ? { initDbStartParams: ["--wal-segsize=1"], postgresqlconf: conf.replace("min_wal_size=32MB", "min_wal_size=2MB").replace("max_wal_size=64MB", "max_wal_size=16MB") } : { postgresqlconf: conf };
const pg = await PGlite.create(opts);
const ws = (await pg.query("show wal_segment_size")).rows[0].wal_segment_size;
const tar = await pg.dumpDataDir("gzip");
const buf = Buffer.from(await tar.arrayBuffer());
writeFileSync(`template-${variant}.tgz`, buf);
console.log(variant, "wal_segment_size", ws, "template", (buf.length / 1e6).toFixed(2), "MB gz");
await pg.close();
