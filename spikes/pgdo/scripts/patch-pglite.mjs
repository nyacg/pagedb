// Workers can't compile WebAssembly at runtime. Emscripten's addFunction does, for JS callbacks:
// convertJsFunctionToWasm builds a tiny module whose bytes depend only on the signature. So:
// 1. rewrite `new WebAssembly.Module(bytes)` there to `globalThis.__pgWasmShim(sig, bytes)` (Node,
//    with no shim installed, still compiles at runtime, so scripts/mkimage.mjs keeps working);
// 2. emit vendor/shims/<sig>.wasm (the same bytes, precompiled at deploy) and src/shims.ts.
//   node scripts/patch-pglite.mjs [extra sigs…]
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
const dist = "node_modules/@electric-sql/pglite/dist";
const re = /convertJsFunctionToWasm=\((\w+),(\w+)\)=>\{var (\w+)=Uint8Array\.of\(([^;]*?)\)[;,](var )?(\w+)=new WebAssembly\.Module\(\3\)/g;
for (const f of readdirSync(dist).filter((f) => f.endsWith(".js"))) {
  const p = `${dist}/${f}`;
  const s = readFileSync(p, "utf8");
  if (!s.includes("convertJsFunctionToWasm")) continue;
  let n = 0, l = 0;
  let out = s.replace(re, (m, fn, sig, bytes, body, v, mod) => (n++, m.replace(`new WebAssembly.Module(${bytes})`, `(globalThis.__pgWasmShim??((s,b)=>new WebAssembly.Module(b)))(${sig},${bytes})`)));
  // Side modules (plpgsql.so, …): Postgres dlopens them and Emscripten compiles their bytes. Swap in
  // the precompiled module for that library first (src/libs.ts, from scripts/extract-libs.mjs).
  out = out.replace(/loadWebAssemblyModule=\((\w+),(\w+),(\w+),(\w+),(\w+)\)=>\{(?!\1=globalThis)/g, (m, bin, flags, lib) => (l++, `${m}${bin}=globalThis.__pgSideModule?.(${lib})??${bin};`));
  // Clocks: Workers freeze time while code runs, so a Postgres loop that waits for the clock to
  // move (pg_sleep) never ends. Let the host substitute both clocks (src/clock.ts).
  let c = 0;
  out = out.replace("_emscripten_date_now=()=>Date.now()", () => (c++, "_emscripten_date_now=()=>(globalThis.__pgDateNow??Date.now)()"));
  out = out.replace("_emscripten_get_now=()=>performance.now()", () => (c++, "_emscripten_get_now=()=>(globalThis.__pgNow??(()=>performance.now()))()"));
  if (n || l || c) writeFileSync(p, out);
  console.log(`${f}: ${n} addFunction, ${l} side-module loader, ${c} clocks patched${s.includes("__pgWasmShim") ? " (already)" : ""}`);
}
// Signature → module bytes, exactly as Emscripten builds them.
const uleb = (e) => [e.length % 128 | 128, e.length >> 7, ...e];
const codes = { i: 127, p: 127, j: 126, f: 125, d: 124, e: 111 };
const pack = (s) => uleb(Array.from(s, (c) => codes[c]));
const bytesFor = (sig) => Uint8Array.of(0, 97, 115, 109, 1, 0, 0, 0, 1, ...uleb([1, 96, ...pack(sig.slice(1)), ...pack(sig[0] === "v" ? "" : sig[0])]), 2, 7, 1, 1, 101, 1, 102, 0, 0, 7, 5, 1, 1, 102, 0, 0);
const sigs = [...new Set(["ppp", "pi", "ipi", "ppi", "ie", "vi", "ii", "iii", "vii", "v", "i", "pp", "vp", "ip", "iip", "pip", ...process.argv.slice(2)])].sort();
for (const s of sigs) writeFileSync(`vendor/shims/${s}.wasm`, bytesFor(s));
writeFileSync(
  "src/shims.ts",
  `// Generated by scripts/patch-pglite.mjs: precompiled addFunction wrappers, by signature.\n${sigs.map((s, i) => `import m${i} from "../vendor/shims/${s}.wasm";`).join("\n")}\nconst shims: Record<string, WebAssembly.Module> = { ${sigs.map((s, i) => `${JSON.stringify(s)}: m${i}`).join(", ")} };\n(globalThis as any).__pgWasmShim = (sig: string, _bytes: Uint8Array) => {\n  const m = shims[sig];\n  if (!m) throw new Error(\`no precompiled wasm shim for signature "\${sig}": add it to scripts/patch-pglite.mjs\`);\n  return m;\n};\nexport {};\n`,
);
console.log(`${sigs.length} shims: ${sigs.join(" ")}`);
