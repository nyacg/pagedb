// Copy PGlite's bundled side modules (Postgres .so files: plpgsql, dict_snowball, …) out of its
// filesystem bundle into vendor/lib/<name>.wasm, so the Worker can import them precompiled
// (Workers can't compile wasm at runtime; Postgres dlopens these on first use).
import { PGlite } from "@electric-sql/pglite";
import { writeFileSync } from "node:fs";
const pg = await PGlite.create();
const dir = "/pglite/lib/postgresql";
const names = pg.mod.FS.readdir(dir).filter((n) => n.endsWith(".so"));
for (const n of names) writeFileSync(`vendor/lib/${n.replace(/\.so$/, "")}.wasm`, pg.mod.FS.readFile(`${dir}/${n}`));
const mods = names.map((n) => n.replace(/\.so$/, ""));
writeFileSync(
  "src/libs.ts",
  `// Generated by scripts/extract-libs.mjs: PGlite's side modules, precompiled, by library name.\n${mods.map((m, i) => `import l${i} from "../vendor/lib/${m}.wasm";`).join("\n")}\nconst libs: Record<string, WebAssembly.Module> = { ${mods.map((m, i) => `${JSON.stringify(m)}: l${i}`).join(", ")} };\n(globalThis as any).__pgSideModule = (libName: string) => libs[String(libName).split("/").pop()!.replace(/\\.so$/, "")];\nexport {};\n`,
);
console.log(`${names.length} side modules: ${names.join(" ")}`);
process.exit(0);
