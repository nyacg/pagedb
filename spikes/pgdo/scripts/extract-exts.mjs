// Unpack PGlite's extension bundles (contrib + pgvector) at build time: each .so becomes a
// precompiled module in vendor/lib (the side-module loader swaps it in by name, as for plpgsql;
// the file itself only has to exist, so it gets a placeholder byte); control and SQL files are
// inlined into src/exts.ts, which writes them into Emscripten's filesystem before Postgres starts.
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, statSync, writeFileSync, copyFileSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";

const NAMES = ["pgcrypto", "uuid-ossp", "pg_trgm", "citext", "hstore", "ltree", "fuzzystrmatch", "unaccent", "btree_gin", "btree_gist", "intarray", "tablefunc", "cube", "earthdistance", "isn", "seg", "tsm_system_rows"];
const bundles = NAMES.map((n) => [n, `node_modules/@electric-sql/pglite/dist/${n}.tar.gz`]);
bundles.push(["vector", "node_modules/@electric-sql/pglite-pgvector/dist/vector.tar.gz"]);

const text = [];
const libs = [];
const walk = (d, base = d) => readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f), base) : [join(d, f).slice(base.length + 1)]));
for (const [name, tgz] of bundles) {
  const dir = mkdtempSync(join(tmpdir(), "pgext-"));
  execFileSync("tar", ["xzf", tgz, "-C", dir]);
  for (const rel of walk(dir)) {
    const dest = `/pglite/${rel}`;
    if (rel.endsWith(".so")) {
      const lib = rel.split("/").pop().replace(/\.so$/, "");
      copyFileSync(join(dir, rel), `vendor/lib/${lib}.wasm`);
      libs.push([lib, dest]);
    } else text.push([dest, readFileSync(join(dir, rel), "utf8")]);
  }
}
const id = (s) => s.replace(/[^a-z0-9]/gi, "_");
writeFileSync(
  "src/exts.ts",
  `// Generated by scripts/extract-exts.mjs: ${bundles.map((b) => b[0]).join(", ")}.
${libs.map(([l]) => `import m_${id(l)} from "../vendor/lib/${l}.wasm";`).join("\n")}

const extLibs: Record<string, WebAssembly.Module> = { ${libs.map(([l]) => `${JSON.stringify(l)}: m_${id(l)}`).join(", ")} };
const core = (globalThis as any).__pgSideModule;
(globalThis as any).__pgSideModule = (libName: string) => core?.(libName) ?? extLibs[String(libName).split("/").pop()!.replace(/\\.so$/, "")];
const files: [string, string][] = [
${text.map(([p, t]) => `  [${JSON.stringify(p)}, ${JSON.stringify(t)}],`).join("\n")}
${libs.map(([, p]) => `  [${JSON.stringify(p)}, "\\0"],`).join("\n")}
];

/** A PGlite extension whose setup writes the files in before Postgres starts. */
export const contrib = {
  name: "contrib",
  setup: async (_pg: unknown, opts: any) => ({
    emscriptenOpts: {
      ...opts,
      preRun: [
        ...(opts.preRun ?? []),
        (mod: any) => {
          for (const [path, data] of files) {
            mod.FS.mkdirTree(path.slice(0, path.lastIndexOf("/")));
            mod.FS.writeFile(path, data);
          }
        },
      ],
    },
  }),
};
`,
);
console.log(`${bundles.length} extensions, ${libs.length} libs, ${text.length} text files`);
